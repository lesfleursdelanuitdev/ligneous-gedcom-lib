package parser

import (
	"strings"

	"golang.org/x/text/unicode/norm"
)

// anselOne maps the single-byte ANSEL characters 0x80-0xFF to Unicode (0 = undefined).
// ANSI/NISO Z39.47 plus the GEDCOM 5.5.1 extensions (BE, BF, CD, CE, CF).
var anselOne = [128]rune{
	0x8D - 0x80: 0x200D, 0x8E - 0x80: 0x200C,
	0xA1 - 0x80: 0x0141, 0xA2 - 0x80: 0x00D8, 0xA3 - 0x80: 0x0110, 0xA4 - 0x80: 0x00DE,
	0xA5 - 0x80: 0x00C6, 0xA6 - 0x80: 0x0152, 0xA7 - 0x80: 0x02B9, 0xA8 - 0x80: 0x00B7,
	0xA9 - 0x80: 0x266D, 0xAA - 0x80: 0x00AE, 0xAB - 0x80: 0x00B1, 0xAC - 0x80: 0x01A0,
	0xAD - 0x80: 0x01AF, 0xAE - 0x80: 0x02BC,
	0xB0 - 0x80: 0x02BB, 0xB1 - 0x80: 0x0142, 0xB2 - 0x80: 0x00F8, 0xB3 - 0x80: 0x0111,
	0xB4 - 0x80: 0x00FE, 0xB5 - 0x80: 0x00E6, 0xB6 - 0x80: 0x0153, 0xB7 - 0x80: 0x02BA,
	0xB8 - 0x80: 0x0131, 0xB9 - 0x80: 0x00A3, 0xBA - 0x80: 0x00F0,
	0xBC - 0x80: 0x01A1, 0xBD - 0x80: 0x01B0, 0xBE - 0x80: 0x25A1, 0xBF - 0x80: 0x25A0,
	0xC0 - 0x80: 0x00B0, 0xC1 - 0x80: 0x2113, 0xC2 - 0x80: 0x2117, 0xC3 - 0x80: 0x00A9,
	0xC4 - 0x80: 0x266F, 0xC5 - 0x80: 0x00BF, 0xC6 - 0x80: 0x00A1, 0xC7 - 0x80: 0x00DF,
	0xC8 - 0x80: 0x20AC, 0xCD - 0x80: 0x0065, 0xCE - 0x80: 0x006F, 0xCF - 0x80: 0x00DF,
}

// anselMark maps the combining bytes 0xE0-0xFE to Unicode combining characters
// (index b-0xE0, 0 = not a combining byte). In ANSEL they come before the base letter.
var anselMark = [31]rune{
	0x0309, 0x0300, 0x0301, 0x0302, 0x0303, 0x0304, 0x0306, 0x0307, // E0-E7
	0x0308, 0x030C, 0x030A, 0xFE20, 0xFE21, 0x0315, 0x030B, 0x0310, // E8-EF
	0x0327, 0x0328, 0x0323, 0x0324, 0x0325, 0x0333, 0x0332, 0x0326, // F0-F7
	0x031C, 0x032E, 0xFE22, 0xFE23, 0x0338, 0, 0x0313, // F8-FE
}

// decodeANSEL converts ANSEL bytes to a Unicode string in NFC form. Combining
// marks are moved after their base letter. Undefined bytes become U+FFFD and
// marks with no base letter are dropped; bad counts both.
func decodeANSEL(b []byte) (s string, bad int) {
	var sb strings.Builder
	sb.Grow(len(b) + 8)
	var marks []rune // pending marks, in input order
	composed := false
	for _, c := range b {
		if c >= 0xE0 && c <= 0xFE && anselMark[c-0xE0] != 0 {
			marks = append(marks, anselMark[c-0xE0])
			continue
		}
		var r rune
		switch {
		case c < 0x80:
			r = rune(c)
		case anselOne[c-0x80] != 0:
			r = anselOne[c-0x80]
		default:
			bad++
			r = 0xFFFD
		}
		if len(marks) > 0 {
			if r >= 0x20 && r != 0x7F && r != 0xFFFD {
				sb.WriteRune(r)
				for _, m := range marks {
					sb.WriteRune(m)
				}
				composed = true
				marks = marks[:0]
				continue
			}
			bad += len(marks) // marks with no usable base letter
			marks = marks[:0]
		}
		sb.WriteRune(r)
	}
	bad += len(marks)
	s = sb.String()
	if composed {
		s = norm.NFC.String(s)
	}
	return s, bad
}
